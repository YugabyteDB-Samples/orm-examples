using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using DapperORM.Models;
using DapperORM.Repositories;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.HttpsPolicy;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Dapper;
using YBNpgsql;

namespace DapperORM
{
    public class Startup
    {
        public Startup(IConfiguration configuration)
        {
            Configuration = configuration;
        }

        public IConfiguration Configuration { get; }

        // This method gets called by the runtime. Use this method to add services to the container.
        public void ConfigureServices(IServiceCollection services)
        {
            services.AddControllers();
            services.AddScoped<IUsersRepository, UsersRepository>();
            services.AddScoped<IProductsRepository, ProductsRepository>();
            services.AddScoped<IOrdersRepository, OrdersRepository>();
            services.AddScoped<IOrderLinesRepository, OrderLinesRepository>();
        }

        // This method gets called by the runtime. Use this method to configure the HTTP request pipeline.
        public void Configure(IApplicationBuilder app, IWebHostEnvironment env)
        {
            if (env.IsDevelopment())
            {
                app.UseDeveloperExceptionPage();
            }

            app.UseHttpsRedirection();

            app.UseRouting();

            app.UseAuthorization();

            app.UseEndpoints(endpoints =>
            {
                endpoints.MapControllers();
            });

            SeedData.Initialize(Configuration.GetConnectionString("DefaultConnection"));
        }

        public static class SeedData
        {
            // Same schema EF Core's EnsureCreated() generated for these models, so existing databases keep working.
            private const string Schema = @"
                CREATE TABLE IF NOT EXISTS users (
                    ""userId"" integer GENERATED BY DEFAULT AS IDENTITY,
                    ""firstName"" text,
                    ""lastName"" text,
                    email text,
                    CONSTRAINT ""PK_users"" PRIMARY KEY (""userId""));
                CREATE TABLE IF NOT EXISTS products (
                    ""productId"" integer GENERATED BY DEFAULT AS IDENTITY,
                    description text,
                    price numeric(10,2) NOT NULL,
                    ""productName"" text,
                    CONSTRAINT ""PK_products"" PRIMARY KEY (""productId""));
                CREATE TABLE IF NOT EXISTS orders (
                    ""orderId"" uuid NOT NULL,
                    ""orderTime"" timestamp without time zone NOT NULL,
                    ""orderTotal"" numeric(10,2) NOT NULL,
                    ""userId"" integer NOT NULL,
                    CONSTRAINT ""PK_orders"" PRIMARY KEY (""orderId""),
                    CONSTRAINT ""FK_orders_users_userId"" FOREIGN KEY (""userId"")
                        REFERENCES users (""userId"") ON DELETE CASCADE);
                CREATE TABLE IF NOT EXISTS orderlines (
                    ""orderId"" uuid NOT NULL,
                    ""productId"" integer NOT NULL,
                    units integer NOT NULL,
                    CONSTRAINT ""PK_orderlines"" PRIMARY KEY (""orderId"", ""productId""),
                    CONSTRAINT ""FK_orderlines_orders_orderId"" FOREIGN KEY (""orderId"")
                        REFERENCES orders (""orderId"") ON DELETE CASCADE,
                    CONSTRAINT ""FK_orderlines_products_productId"" FOREIGN KEY (""productId"")
                        REFERENCES products (""productId"") ON DELETE CASCADE);
                CREATE INDEX IF NOT EXISTS ""IX_orders_userId"" ON orders (""userId"");
                CREATE INDEX IF NOT EXISTS ""IX_orderlines_productId"" ON orderlines (""productId"");";

            public static void Initialize(string connectionString)
            {
                using (var connection = new NpgsqlConnection(connectionString))
                {
                    connection.Execute(Schema);
                }
            }
        }
    }
}
